"""
Failure patterns for the synthetic maintenance dataset.

Each equipment type has several failure modes. A mode defines:
  cause    - the true root cause (what the diagnosis agent should find)
  symptoms - different ways a user might describe the problem
  fix      - ordered repair steps
  parts    - parts that may be used
  cost     - (min, max) repair cost in INR
  hours    - (min, max) downtime / repair time in hours
  urgency  - Low / Medium / High / Critical
  safety   - True if this failure is safety-critical (escalate to a human)

Add more modes or equipment here and re-run generate_dataset.py.
"""


def m(cause, symptoms, fix, parts, cost, hours, urgency, safety=False):
    return dict(cause=cause, symptoms=symptoms, fix=fix, parts=parts,
                cost=cost, hours=hours, urgency=urgency, safety=safety)


